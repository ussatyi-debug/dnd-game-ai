//! Полные листы и инвентари отряда по листу персонажей «Дом Стрэндж» на День 82.
//!
//! Правила переноса: в лист попадает только то, что в нём написано. Где лист расходится
//! с правилами 5e, остаётся значение листа (он главный по механике), а расхождение
//! записывается в `notes`. Владения, взятые из правил класса, помечены `from_rules`.

use crate::character::Ability;
use crate::inventory::{Container, Inventory, NewItem, ON_PERSON};
use crate::profile::{
    Attack, Attunement, Bonus, Feature, HitDice, Proficiency, ProficiencyLine, Profile, Skill,
    SkillEntry,
};

fn skill(skill: Skill, proficiency: Proficiency, source: &str) -> SkillEntry {
    SkillEntry {
        skill,
        proficiency,
        source: source.into(),
        bonuses: Vec::new(),
        advantage: Vec::new(),
    }
}

fn with_bonus(mut entry: SkillEntry, label: &str, value: i32) -> SkillEntry {
    entry.bonuses.push(Bonus::new(label, value));
    entry
}

fn with_advantage(mut entry: SkillEntry, when: &[&str]) -> SkillEntry {
    entry.advantage.extend(when.iter().map(|s| (*s).to_string()));
    entry
}

fn weapon(name: &str, ability: Ability, proficient: Option<bool>, magic: i32) -> Attack {
    Attack {
        name: name.into(),
        ability: Some(ability),
        caster_id: None,
        proficient,
        magic,
        damage_dice: String::new(),
        damage_type: String::new(),
        add_ability_to_damage: true,
        damage_bonus: 0,
        extra: String::new(),
        range: String::new(),
        notes: String::new(),
    }
}

fn damage(mut attack: Attack, dice: &str, kind: &str, extra: &str) -> Attack {
    attack.damage_dice = dice.into();
    attack.damage_type = kind.into();
    attack.extra = extra.into();
    attack
}

fn range_notes(mut attack: Attack, range: &str, notes: &str) -> Attack {
    attack.range = range.into();
    attack.notes = notes.into();
    attack
}

fn feature(name: &str, source: &str, text: &str, resource: Option<&str>) -> Feature {
    Feature {
        name: name.into(),
        source: source.into(),
        text: text.into(),
        resource_id: resource.map(Into::into),
    }
}

fn prof(kind: &str, text: &str, from_rules: bool) -> ProficiencyLine {
    ProficiencyLine { kind: kind.into(), text: text.into(), from_rules }
}

fn attuned(name: &str, effect: &str) -> Attunement {
    Attunement { name: name.into(), effect: effect.into() }
}

fn dice(die: u32, total: u32) -> HitDice {
    HitDice { die, current: total, total }
}

fn stock(inv: &mut Inventory, container: &str, category: &str, items: &[(&str, u32, &str)]) {
    for (name, quantity, notes) in items {
        inv.add(NewItem {
            name: (*name).into(),
            quantity: *quantity,
            container: container.into(),
            category: category.into(),
            notes: (*notes).into(),
        })
        .expect("предметы демо-листа корректны");
    }
}

