/** Все теги для вида (общие + свои). */
export function tagsFor(species: string | null): string[] {
  const common = Object.values(APPEARANCE_TAGS).flat();
  return [...(species ? (SPECIES_TAGS[species] ?? []) : []), ...common];
}

/** Случайные 13 тегов (свои теги вида — чаще). */
export function randomTags(species: string | null, count = 13, random: () => number = Math.random): string[] {
  const own = species ? (SPECIES_TAGS[species] ?? []) : [];
  const common = Object.values(APPEARANCE_TAGS).flat();
  const pick = (list: string[], n: number) => {
    const copy = [...list];
    const out: string[] = [];
    while (copy.length && out.length < n) out.push(copy.splice(Math.floor(random() * copy.length), 1)[0] as string);
    return out;
  };
  const fromOwn = pick(own, Math.min(3, own.length));
  return [...fromOwn, ...pick(common, count - fromOwn.length)];
}
